document.addEventListener("click", function (event) {
  const target = event.target.closest("button, a");
  if (!target) return;
  if (target.matches("[data-add]")) addToCart(target.dataset.add);
  if (target.matches("[data-increase]")) changeQuantity(target.dataset.increase, 1);
  if (target.matches("[data-decrease]")) changeQuantity(target.dataset.decrease, -1);
  if (target.matches("[data-open-cart]")) openCart();
  if (target.matches("[data-close-cart]")) closeCart();
  if (target.matches("[data-close-modal]")) closeModal();
  if (target.matches("[data-open-modal]")) openModal(target.dataset.openModal);
  if (target.matches("[data-order]")) {
    if (!cart.size) {
      showToast("Сначала добавьте блюда в корзину");
    } else {
      openModal("order");
    }
  }
  if (target.matches(".menu-category")) {
    activeCategory = target.dataset.category;
    document.querySelectorAll(".menu-category").forEach(function (button) {
      const active = button === target;
      button.classList.toggle("is-active", active);
      button.setAttribute("aria-selected", String(active));
    });
    renderMenu();
  }
  if (target.matches("[data-scroll-top]")) window.scrollTo({ top: 0, behavior: "smooth" });
  if (target.matches(".menu-toggle")) {
    const header = document.querySelector(".site-header");
    header.classList.toggle("nav-open");
    target.setAttribute("aria-expanded", String(header.classList.contains("nav-open")));
  }
  if (target.closest(".main-nav a")) {
    const header = document.querySelector(".site-header");
    header.classList.remove("nav-open");
    document.querySelector(".menu-toggle").setAttribute("aria-expanded", "false");
  }
});

