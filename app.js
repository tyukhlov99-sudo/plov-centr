function formatPrice(value) {
  if (value === null) return "Цена уточняется";
  return new Intl.NumberFormat("ru-RU").format(value) + " ₽";
}

function findItem(id) {
  return catalog.find(function (item) { return item.id === id; });
}

function dishImage(item) {
  return item.image
    ? '<img src="./assets/' + item.image + '" alt="' + item.name + '" loading="lazy" />'
    : '<div class="dish-photo-pending"><span aria-hidden="true">◇</span><small>Фото скоро</small></div>';
}

function renderMenu() {
  const items = catalog.filter(function (item) { return item.category === activeCategory; });
  menuGrid.innerHTML = items.map(function (item) {
    const tag = item.tag ? '<span class="dish-tag">' + item.tag + '</span>' : "";
    return '<article class="menu-card">' +
      '<div class="menu-card-image">' + dishImage(item) + tag + '</div>' +
      '<div class="menu-card-content"><h3>' + item.name + '</h3><p>' + item.description + '</p>' +
      '<div class="menu-card-bottom"><span class="dish-price">' + formatPrice(item.price) + '</span>' +
      (item.price === null ? '<span class="price-pending-note">Уточните в ресторане</span>' :
      '<button class="add-button" type="button" data-add="' + item.id + '" aria-label="Добавить ' + item.name + (item.description ? ', ' + item.description : '') + ' в корзину">В корзину <span>+</span></button>') + '</div></div></article>';
  }).join("");
}

function renderCart() {
  const entries = Array.from(cart.values());
  const quantity = entries.reduce(function (sum, entry) { return sum + entry.quantity; }, 0);
  const total = entries.reduce(function (sum, entry) { return sum + entry.item.price * entry.quantity; }, 0);
  cartCount.textContent = quantity;
  cartTotal.textContent = formatPrice(total);
  if (!entries.length) {
    cartItems.innerHTML = '<div class="cart-empty"><div><span>+</span><h3>Корзина пуста</h3><p>Добавьте блюда из меню, чтобы оформить заказ.</p></div></div>';
    return;
  }
  cartItems.innerHTML = entries.map(function (entry) {
    const item = entry.item;
    const lineTotal = item.price * entry.quantity;
    return '<article class="cart-item">' + dishImage(item) +
      '<div><h3>' + item.name + (item.description ? ' · ' + item.description : '') + '</h3><span class="cart-item-price">' + formatPrice(item.price) + '</span>' +
      '<div class="quantity-control"><button type="button" data-decrease="' + item.id + '" aria-label="Убрать одну порцию">−</button><b>' + entry.quantity + '</b><button type="button" data-increase="' + item.id + '" aria-label="Добавить ещё порцию">+</button></div></div>' +
      '<b class="cart-item-total">' + formatPrice(lineTotal) + '</b></article>';
  }).join("");
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("is-visible");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(function () {
    toast.classList.remove("is-visible");
  }, 2800);
}

function addToCart(id, shouldToast) {
  const item = findItem(id);
  if (!item || !Number.isFinite(item.price)) return;
  const present = cart.get(id);
  cart.set(id, { item: item, quantity: present ? present.quantity + 1 : 1 });
  renderCart();
  if (shouldToast !== false) showToast(item.name + " добавлен в корзину");
}

function changeQuantity(id, delta) {
  const entry = cart.get(id);
  if (!entry) return;
  const nextQuantity = entry.quantity + delta;
  if (nextQuantity <= 0) cart.delete(id);
  else cart.set(id, { item: entry.item, quantity: nextQuantity });
  renderCart();
}

function revealOverlay() {
  overlay.hidden = false;
  requestAnimationFrame(function () { overlay.classList.add("is-visible"); });
  document.body.classList.add("is-locked");
}

function hideOverlayIfUnused() {
  const noPanels = !cartDrawer.classList.contains("is-open") && !modal.classList.contains("is-open");
  if (noPanels) {
    overlay.classList.remove("is-visible");
    window.setTimeout(function () { if (!overlay.classList.contains("is-visible")) overlay.hidden = true; }, 250);
    document.body.classList.remove("is-locked");
  }
}

function openCart() {
  closeModal(false);
  revealOverlay();
  cartDrawer.classList.add("is-open");
  cartDrawer.setAttribute("aria-hidden", "false");
}

function closeCart() {
  cartDrawer.classList.remove("is-open");
  cartDrawer.setAttribute("aria-hidden", "true");
  hideOverlayIfUnused();
}

function cartPreviewMarkup() {
  const entries = Array.from(cart.values());
  const total = entries.reduce(function (sum, entry) { return sum + entry.item.price * entry.quantity; }, 0);
  return '<h3>Ваш заказ</h3>' + entries.map(function (entry) {
    return '<p><span>' + entry.item.name + (entry.item.description ? ' · ' + entry.item.description : '') + ' × ' + entry.quantity + '</span><b>' + formatPrice(entry.item.price * entry.quantity) + '</b></p>';
  }).join("") + '<p><span>Итого</span><b>' + formatPrice(total) + '</b></p>';
}

